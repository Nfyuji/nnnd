def is_likely_store(name: str) -> bool:
    """Reject obvious non-retail businesses returned by broad search engines."""
    normalized = " ".join((name or "").lower().split())
    return len(normalized) >= 3 and not any(
        word in normalized for word in EXCLUDED_BUSINESS_WORDS
    )
